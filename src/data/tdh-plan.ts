/**
 * True room-by-room geometry for Tokyo Disneyland Hotel.
 *
 * Traced from the fully numbered floor plan published on the hotel room pages:
 * the drawing was segmented into regions, each region reduced to a polygon, and
 * the room numbers assigned by walking each corridor from a seed room. Every
 * one of the 116 positions is therefore in its real place, at its real size and
 * angle — the family rooms come out about three times the area of a standard
 * room, which is what 93 m² against 40 m² should look like.
 *
 * Coordinates are in plan units (roughly 1 unit ≈ 0.55 m) with the park at the
 * bottom and the main entrance courtyard at the top. The 8F bridge (401–407)
 * comes from the 8F plan, registered onto the same drawing to under 2 px.
 *
 * A position can change room type by floor — 517 is a standard alcove room on
 * 5–6F, a concierge alcove room on 7F and a concierge superior room on 8–9F — so
 * the label here describes the position and the exact name per floor is resolved
 * from the room-number dataset.
 */

